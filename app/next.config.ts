import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  experimental: {
    agentFeedback: true,
  },
  cacheComponents: true,
  partialPrefetching: true,
  async headers() {
    return [
      {
        // The document references content-hashed chunks; a cached HTML
        // silently pins visitors to a dead build. Always revalidate it.
        source: "/",
        headers: [{ key: "Cache-Control", value: "no-cache" }],
      },
    ];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;

// Emulate Cloudflare bindings inside `next dev` only. `next start` and
// `next build` must not load it — it spins up miniflare and monkey-patches
// the runtime, which breaks the plain Node server.
if (process.env.NODE_ENV === "development") {
  import("@opennextjs/cloudflare").then((m) =>
    m.initOpenNextCloudflareForDev(),
  );
}
